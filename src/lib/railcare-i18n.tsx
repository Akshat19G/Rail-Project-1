const DICTS: Record<LocaleCode, Dict> = { en, hi, mr, bn, ta, te, gu, kn };

const KEY = "railcare.locale";

type Ctx = { locale: LocaleCode; setLocale: (l: LocaleCode) => void; t: (key: string) => string };

const I18nContext = createContext<Ctx | null>(null);

export function RailCareI18nProvider({ children }: { children: ReactNode }) {
  const [locale, setLocaleState] = useState<LocaleCode>("en");

  useEffect(() => {
    const saved = localStorage.getItem(KEY) as LocaleCode | null;
    if (saved && saved in DICTS) setLocaleState(saved);
  }, []);

  const setLocale = useCallback((l: LocaleCode) => {
    setLocaleState(l);
    try {
      localStorage.setItem(KEY, l);
    } catch {
      /* ignore */
    }
    if (typeof document !== "undefined") document.documentElement.lang = l;
  }, []);

  const t = useCallback((key: string) => DICTS[locale]?.[key] ?? en[key] ?? key, [locale]);

  const value = useMemo(() => ({ locale, setLocale, t }), [locale, setLocale, t]);
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error("useI18n must be used inside RailCareI18nProvider");
  return ctx;
}
